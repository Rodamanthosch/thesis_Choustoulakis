pip install --index-url https://pypi.org/simple \
            --extra-index-url https://download.pytorch.org/whl/cu124 \
            -r "$LOCK"

# mamba_ssm/utils/generation.py imports transformers classes that newer transformers
# removed; patch by path (importing mamba_ssm would fail first).
GEN=$(ls "$VENV"/lib/python3.12/site-packages/mamba_ssm/utils/generation.py)
python - "$GEN" <<'EOF'
import sys
p = sys.argv[1]
src = open(p).read()
new = src.replace(
    "from transformers.generation import GreedySearchDecoderOnlyOutput, SampleDecoderOnlyOutput, TextStreamer",
    "from transformers.generation import GenerateDecoderOnlyOutput, TextStreamer",
).replace(
    "output_cls = GreedySearchDecoderOnlyOutput if top_k == 1 else SampleDecoderOnlyOutput",
    "output_cls = GenerateDecoderOnlyOutput",
)
if new != src:
    open(p, "w").write(new)
    print("patched", p)
else:
    print("no patch needed", p)
EOF

# ---- 5. C headers for Triton on compute nodes ---------------------------------------------
log "5/7 C headers -> $JIM_ROOT/glibc-headers"
HDR=$JIM_ROOT/glibc-headers/include
if command -v rpm >/dev/null && rpm -q glibc-headers >/dev/null 2>&1; then
  for pkg in glibc-headers glibc-devel kernel-headers; do
    rpm -q "$pkg" >/dev/null 2>&1 || continue
    rpm -ql "$pkg" | grep '^/usr/include/' | while read -r f; do
      [ -f "$f" ] && install -D -m644 "$f" "$HDR/${f#/usr/include/}"
    done
  done
  echo "$(find "$HDR" -type f | wc -l) header files in $HDR"
else
  echo "rpm / glibc-headers not found on this login node: skipped (only matters if"
  echo "compute nodes lack /usr/include AND you train vmamba2)"
fi
command -v gcc >/dev/null && echo "gcc: $(gcc --version | head -1)" \
  || echo "WARNING: no gcc on this node; Triton (vmamba2) needs gcc on the compute nodes"

# ---- 6. FID tooling, fetched now so compute nodes need no internet -------------------------
log "6/7 FID: LTH14 torch-fidelity fork, JiT reference stats, Inception weights"
cd "$REPO"
python - <<'EOF'
import subprocess, sys
from src.utils import JIT_TORCH_FIDELITY, _has_jit_torch_fidelity, jit_fid_stats_path
if not _has_jit_torch_fidelity():
    subprocess.check_call([sys.executable, "-m", "pip", "install", "-q",
                           "--force-reinstall", "--no-deps", JIT_TORCH_FIDELITY])
for size in (256, 512):
    print("stats ok:", jit_fid_stats_path(size))
EOF
python - <<'EOF' || echo "WARNING: Inception prefetch failed; evaluate.py will download it at first use"
from torch_fidelity.feature_extractor_inceptionv3 import FeatureExtractorInceptionV3
FeatureExtractorInceptionV3("inception-v3-compat", ["2048", "logits_unbiased"])
print("torch-fidelity Inception weights cached")
EOF
cd "$JIM_ROOT"

# ---- 7. check -------------------------------------------------------------------------------
log "7/7 import check"
python - <<'EOF'
import torch, torchvision, triton, mamba_ssm, causal_conv1d, torch_fidelity
print("torch", torch.__version__, "| torchvision", torchvision.__version__,
      "| triton", triton.__version__, "| mamba_ssm", mamba_ssm.__version__,
      "| causal_conv1d", causal_conv1d.__version__)
print("CUDA visible here:", torch.cuda.is_available(), "(False is normal on a login node)")
EOF
du -sh "$JIM_ROOT" 2>/dev/null | sed 's/^/size of JIM_ROOT: /'
echo
echo "Done. In every session / Slurm job:   source $JIM_ROOT/env.sh"
echo "Next: bash setup_data.sh   (then a GPU check, e.g. python scripts/check_vmamba2_cuda.py on a GPU node)"
