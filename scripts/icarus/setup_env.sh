#!/bin/bash
# =============================================================================
# setup_env.sh -- build the JiT / JiM environment on Icarus, entirely inside ONE folder.
#
#   bash setup_env.sh                    # default root: /nfs/scratch/prod-2026-17/n.spanos/jim
#   JIM_ROOT=/some/other/dir bash setup_env.sh
#
# Run on the LOGIN node (needs internet). Safe to re-run: every step skips what is done.
# Writes nothing outside $JIM_ROOT (python, venv, pip/torch/triton caches, TMPDIR, the
# repo, the Claude config all live there). Afterwards, in every session / Slurm job:
#   source $JIM_ROOT/env.sh
#
# Layout it creates:
#   $JIM_ROOT/env.sh                   source this (paths, caches, venv)
#   $JIM_ROOT/thesis_Choustoulakis/    the repo (cloned from GitHub)
#   $JIM_ROOT/python/                  standalone CPython 3.12 (uv-managed, no system module)
#   $JIM_ROOT/envs/jim/                the venv (torch 2.5.1+cu124, mamba-ssm 2.2.4, ...)
#   $JIM_ROOT/cache/ tmp/ tools/       pip / torch / triton caches, TMPDIR, the uv binary
#   $JIM_ROOT/glibc-headers/           C headers for Triton, in case compute nodes lack them
#   $JIM_ROOT/data/ runs/ logs/        filled by setup_data.sh and the training jobs
# =============================================================================
set -euo pipefail

JIM_ROOT=${JIM_ROOT:-/nfs/scratch/prod-2026-17/n.spanos/jim}
REPO_URL=https://github.com/Rodamanthosch/thesis_Choustoulakis.git
PY_VERSION=3.12               # the mamba-ssm / causal-conv1d wheels below are cp312

mkdir -p "$JIM_ROOT"/{tools,python,envs,cache,tmp,data,runs,logs,.config}
cd "$JIM_ROOT"
log() { echo "=== [$(date '+%F %T')] $*"; }

# ---- 1. env.sh: every path and cache inside $JIM_ROOT --------------------------------
log "1/7 writing $JIM_ROOT/env.sh"
{
  echo "# Source in every session and Slurm job:  source $JIM_ROOT/env.sh"
  echo "# Generated by setup_env.sh. Everything lives under JIM_ROOT."
  echo "export JIM_ROOT=$JIM_ROOT"
  cat <<'EOF'
export REPO=$JIM_ROOT/thesis_Choustoulakis
export DATA=$JIM_ROOT/data
export RUNS=$JIM_ROOT/runs
export VENV=$JIM_ROOT/envs/jim

export TMPDIR=$JIM_ROOT/tmp TEMP=$JIM_ROOT/tmp TMP=$JIM_ROOT/tmp
export XDG_CACHE_HOME=$JIM_ROOT/cache
export XDG_CONFIG_HOME=$JIM_ROOT/.config
export PIP_CACHE_DIR=$JIM_ROOT/cache/pip
export PIP_DISABLE_PIP_VERSION_CHECK=1
export UV_CACHE_DIR=$JIM_ROOT/cache/uv
export UV_PYTHON_INSTALL_DIR=$JIM_ROOT/python
export MPLCONFIGDIR=$JIM_ROOT/cache/matplotlib
export TORCH_HOME=$JIM_ROOT/cache/torch
export TRITON_HOME=$JIM_ROOT/cache
export TRITON_CACHE_DIR=$JIM_ROOT/cache/triton
export HF_HOME=$JIM_ROOT/cache/huggingface
export CUDA_CACHE_PATH=$JIM_ROOT/cache/nv
export PYTHONUSERBASE=$JIM_ROOT/.local
export PYTHONNOUSERSITE=1
export PYTHON_HISTORY=$JIM_ROOT/.python_history
export CLAUDE_CONFIG_DIR=$JIM_ROOT/.claude
export PATH=$JIM_ROOT/tools:$PATH
mkdir -p "$TMPDIR" "$MPLCONFIGDIR" "$CLAUDE_CONFIG_DIR"

# Triton (vmamba2's Mamba-2 kernels) gcc-compiles a small launcher at first use. If the
# compute nodes ship no /usr/include, it uses these headers copied from the login node.
if [ -d "$JIM_ROOT/glibc-headers/include" ]; then
  export C_INCLUDE_PATH=${C_INCLUDE_PATH:+$C_INCLUDE_PATH:}$JIM_ROOT/glibc-headers/include
fi

# Claude Code bundled with the VS Code extension (if installed on this cluster).
claude() {
  local bin
  bin=$(ls -d ~/.vscode-server/extensions/anthropic.claude-code-*/resources/native-binary/claude 2>/dev/null | sort -V | tail -1)
  [ -n "$bin" ] || { echo "claude: VS Code Claude Code extension not found" >&2; return 127; }
  "$bin" "$@"
}

if [ -f "$VENV/bin/activate" ]; then
  source "$VENV/bin/activate"
fi
cd "$REPO" 2>/dev/null || true
EOF
} > "$JIM_ROOT/env.sh"
source "$JIM_ROOT/env.sh"
cd "$JIM_ROOT"

# ---- 2. the repo -----------------------------------------------------------------------
log "2/7 repo -> $REPO"
if [ ! -d "$REPO/.git" ]; then
  git clone "$REPO_URL" "$REPO"
else
  echo "already cloned (not pulling: your working tree is left as is)"
fi
git -C "$REPO" config user.name  "Rodamanthos Choustoulakis"
git -C "$REPO" config user.email "rodch51@gmail.com"

# ---- 3. standalone Python 3.12 (no dependence on the cluster's modules) -------------------
log "3/7 python $PY_VERSION -> $JIM_ROOT/python"
if [ ! -x "$JIM_ROOT/tools/uv" ]; then
  curl -LsSf https://astral.sh/uv/install.sh \
    | env UV_INSTALL_DIR="$JIM_ROOT/tools" UV_NO_MODIFY_PATH=1 sh
fi
uv python install "$PY_VERSION"
PY=$(uv python find "$PY_VERSION")
echo "python: $PY ($("$PY" --version))"

# ---- 4. venv + pinned packages (the exact set tested on ARIS) ------------------------------
log "4/7 venv -> $VENV"
if [ ! -f "$VENV/bin/activate" ]; then
  "$PY" -m venv "$VENV"
fi
source "$VENV/bin/activate"
python -m pip install --upgrade pip wheel

LOCK=$JIM_ROOT/requirements-lock.txt
cat > "$LOCK" <<'EOF'
